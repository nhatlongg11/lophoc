async function nav(page: Page, name: string) {
  await page.locator('.topbar').waitFor({ state: 'visible' })
  const navigation = page.getByRole('navigation', { name: 'Điều hướng chính' })
  if (!await navigation.isVisible()) await page.getByRole('button', { name: 'Mở trình đơn', exact: true }).click()
  await navigation.getByRole('button', { name, exact: true }).click()
}
async function post(request: APIRequestContext, path: string, data?: unknown) {
  const token = (await (await request.get('/api/csrf')).json()).token
  const response = await request.post('/api' + path, { headers: { 'X-CSRF-TOKEN': token }, data })
  expect(response.ok(), await response.text()).toBeTruthy()
  return response.json()
}
