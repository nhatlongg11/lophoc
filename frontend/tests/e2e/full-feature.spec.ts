test('D–E weekly recurrence, one occurrence reschedule and persisted parent attendance', async ({ browser }) => {
  const tc = await browser.newContext(), sc = await browser.newContext(), pc = await browser.newContext()
  const teacher = await tc.newPage(), student = await sc.newPage(), parent = await pc.newPage()
  await login(teacher, 'giaovien@lophoc.local')
  const rules = await (await teacher.request.get('/api/timetable/recurrences')).json()
  const minute = 600 + rules.filter((r: { title: string }) => r.title.startsWith('Weekly E2E')).length * 50
  const asTime = (value: number) => String(Math.floor(value / 60)).padStart(2, '0') + ':' + String(value % 60).padStart(2, '0')
  const startTime = asTime(minute), endTime = asTime(minute + 45)
  await nav(teacher, 'Thời khóa biểu')
  await teacher.getByText('Lịch lặp hằng tuần & ngày nghỉ', { exact: true }).click()
  await teacher.getByRole('button', { name: 'Tạo lịch hằng tuần' }).click()
  const dialog = teacher.getByRole('dialog'), title = 'Weekly E2E ' + Date.now()
  const now = new Date(), monday = new Date(now.getFullYear(), now.getMonth(), now.getDate() + (8 - (now.getDay() || 7)))
  const date = (d: Date) => new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' }).format(d)
  const end = new Date(monday); end.setDate(end.getDate() + 21)
  const tuesday = new Date(monday); tuesday.setDate(tuesday.getDate() + 1)
  await dialog.getByLabel('Tên bài học').fill(title)
  await dialog.getByRole('combobox', { name: 'Lớp', exact: true }).selectOption({ label: '8A2' })
  await dialog.getByLabel('Áp dụng từ ngày').fill(date(monday))
  await dialog.getByLabel('Đến ngày').fill(date(end))
  await dialog.getByLabel('Bắt đầu', { exact: true }).fill(startTime)
  await dialog.getByLabel('Kết thúc', { exact: true }).fill(endTime)
  await dialog.getByRole('button', { name: 'Lưu lịch hằng tuần' }).click()
  await expect(dialog).toBeHidden()
  const lessons = await (await teacher.request.get('/api/lessons?from=' + date(monday) + '&to=' + date(tuesday))).json()
  const lesson = lessons.find((l: { title: string }) => l.title === title)
  expect(lesson.starts_at).toContain(date(monday))
  const csrf = (await (await teacher.request.get('/api/csrf')).json()).token
  expect((await teacher.request.put('/api/lessons/' + lesson.id, { headers: { 'X-CSRF-TOKEN': csrf }, data: { ...lesson, starts_at: date(tuesday) + 'T' + startTime, ends_at: date(tuesday) + 'T' + endTime, status: 'rescheduled' } })).ok()).toBeTruthy()
  await login(student, 'hocsinh@lophoc.local')
  const changed = await (await student.request.get('/api/lessons?from=' + date(monday) + '&to=' + date(tuesday))).json()
  expect(changed.find((l: { id: number }) => l.id === lesson.id).starts_at).toContain(date(tuesday))
  const next = new Date(monday); next.setDate(next.getDate() + 7)
  const nextLessons = await (await student.request.get('/api/lessons?from=' + date(next) + '&to=' + date(next))).json()
  expect(nextLessons.find((l: { title: string }) => l.title === title).starts_at).toContain(date(next))
  await nav(teacher, 'Điểm danh')
  await teacher.getByLabel('Chọn tiết học').selectOption(String(lesson.id))
  const me = await (await student.request.get('/api/me')).json()
  await teacher.getByLabel('Trạng thái của ' + me.name, { exact: true }).selectOption('excused')
  await teacher.getByLabel('Ghi chú cho ' + me.name, { exact: true }).fill('Parent notified E2E')
  await teacher.getByRole('button', { name: 'Xác nhận điểm danh' }).click()
  await parentUnlock(parent)
  const attendance = parent.locator('section').filter({ has: parent.getByRole('heading', { name: 'Điểm danh', exact: true }) })
  await expect(attendance.getByText(title, { exact: true })).toBeVisible()
  await expect(attendance.locator('.list-row').filter({ hasText: title }).getByText('Vắng có phép', { exact: true })).toBeVisible()
  await parent.screenshot({ path: 'tests/artifacts/parent-attendance-progress.png', fullPage: true })
  expect((await new AxeBuilder({ page: parent }).analyze()).violations).toEqual([])
  await tc.close(); await sc.close(); await pc.close()
})

