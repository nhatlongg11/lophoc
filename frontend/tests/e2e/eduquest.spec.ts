test('past attendance is read only for teachers while today and admin corrections remain editable', async ({ page, browser }) => {
  const adminContext = await browser.newContext()
  const admin = await adminContext.newPage()
  await login(admin, 'admin@lophoc.local')
  await expect(admin.getByRole('heading', { name: /Chào/ })).toBeVisible()
  await login(page, 'giaovien@lophoc.local')
  await expect(page.getByRole('heading', { name: /Chào/ })).toBeVisible()
  const teacher = await (await page.request.get('/api/me')).json()
  const student = (await (await admin.request.get('/api/users?role=student')).json()).find((s: { email: string }) => s.email === 'hocsinh@lophoc.local')
  const subject = (await (await admin.request.get('/api/subjects')).json())[0]
  const adminCsrf = (await (await admin.request.get('/api/csrf')).json()).token
  const teacherCsrf = (await (await page.request.get('/api/csrf')).json()).token
  const schoolDate = (offset: number) => new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' }).format(new Date(Date.now() + offset * 86400000))
  async function lessonOn(day: string, label: string) {
    const lessons = await (await admin.request.get('/api/lessons?from=' + day + '&to=' + day)).json()
    const existing = lessons.find((l: { title: string; student_ids: number[] }) => l.title === label && l.student_ids.includes(student.id))
    if (existing) return existing
    const response = await admin.request.post('/api/lessons', { headers: { 'X-CSRF-TOKEN': adminCsrf }, data: { title: label, student_ids: [student.id], subject_id: subject.id, teacher_id: teacher.id, starts_at: day + 'T06:00:00', ends_at: day + 'T06:45:00', status: 'scheduled' } })
    expect(response.status()).toBe(201)
    return response.json()
  }
  const past = await lessonOn(schoolDate(-1), 'Điểm danh ngày đã qua E2E')
  const today = await lessonOn(schoolDate(0), 'Điểm danh hôm nay E2E')
  expect((await admin.request.post('/api/lessons/' + past.id + '/attendance', { headers: { 'X-CSRF-TOKEN': adminCsrf }, data: { records: [{ student_id: student.id, status: 'unexcused', note: 'Vắng không phép đã ghi nhận' }] } })).ok()).toBeTruthy()

  await page.getByRole('navigation').getByRole('button', { name: 'Điểm danh', exact: true }).click()
  await page.getByLabel('Chọn tiết học').selectOption(String(past.id))
  await expect(page.getByText('Điểm danh của ngày đã qua đã được khóa.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Xác nhận điểm danh' })).toBeDisabled()
  await expect(page.getByLabel('Trạng thái của ' + student.name, { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Ghi chú cho ' + student.name, { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Trạng thái của ' + student.name, { exact: true })).toHaveValue('unexcused')
  const bypass = await page.request.post('/api/lessons/' + past.id + '/attendance', { headers: { 'X-CSRF-TOKEN': teacherCsrf }, data: { can_edit: true, records: [{ student_id: student.id, status: 'present', note: 'Attempted bypass' }] } })
  expect(bypass.status()).toBe(403)
  const persisted = await (await page.request.get('/api/lessons/' + past.id + '/attendance')).json()
  expect(persisted.students.find((s: { id: number }) => s.id === student.id).status).toBe('unexcused')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'tests/artifacts/attendance-date-locked.png', fullPage: true })

  await page.getByLabel('Chọn tiết học').selectOption(String(today.id))
  await expect(page.getByRole('button', { name: 'Xác nhận điểm danh' })).toBeEnabled()
  await expect(page.getByLabel('Trạng thái của ' + student.name, { exact: true })).toBeEnabled()
  await expect(page.getByLabel('Ghi chú cho ' + student.name, { exact: true })).toBeEnabled()
  await expect(page.locator('.attendance-lock')).toHaveCount(0)

  await admin.getByRole('navigation').getByRole('button', { name: 'Điểm danh', exact: true }).click()
  await admin.getByLabel('Chọn tiết học').selectOption(String(past.id))
  await expect(admin.getByRole('button', { name: 'Xác nhận điểm danh' })).toBeEnabled()
  await expect(admin.getByLabel('Trạng thái của ' + student.name, { exact: true })).toBeEnabled()
  await adminContext.close()
})
