  await expect(dialog.getByRole('heading', { name: 'Hoàn thành thử thách!' })).toBeVisible()
  await expect(dialog.getByText(/2\/2 câu đúng/)).toBeVisible()
  const awarded = Number((await dialog.getByText(/2\/2 câu đúng/).innerText()).match(/\+(\d+) XP/)?.[1])
  expect([0, 50]).toContain(awarded)
  await dialog.getByRole('button', { name: 'Về thư viện' }).click()
