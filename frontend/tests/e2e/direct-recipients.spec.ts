import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, email: string) {
  await page.goto('/app/')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Mật khẩu', { exact: true }).fill('MatKhau123!')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Chào/ })).toBeVisible()
}

test('teachers select multiple students directly and only their official homework counts as completed', async ({ browser }) => {
  test.setTimeout(120_000)
  const teacherContext = await browser.newContext(), studentContext = await browser.newContext(), outsiderContext = await browser.newContext()
  const teacher = await teacherContext.newPage(), student = await studentContext.newPage(), outsider = await outsiderContext.newPage()
  const errors: string[] = [], classRequests: string[] = []
  teacher.on('pageerror', error => errors.push(error.message))
  teacher.on('request', request => { if (request.url().includes('/api/classes')) classRequests.push(request.url()) })
  await login(teacher, 'giaovien@lophoc.local')
  const nav = teacher.getByRole('navigation', { name: 'Điều hướng chính' })
  await expect(nav.getByRole('button', { name: /Lớp/ })).toHaveCount(0)
  await nav.getByRole('button', { name: 'Học sinh', exact: true }).click()
  await expect(teacher.getByRole('cell', { name: 'hocsinh@lophoc.local', exact: true })).toBeVisible()
  await nav.getByRole('button', { name: 'Bài tập', exact: true }).click()
  await teacher.getByRole('button', { name: 'Lớp 5', exact: true }).click()
  await teacher.getByRole('button', { name: 'Tạo bài tập có câu hỏi' }).click()
  const dialog = teacher.getByRole('dialog'), title = 'Direct students ' + Date.now()
  await dialog.getByLabel('Tên bài tập').fill(title)
  await expect(dialog.getByRole('button', { name: 'Giao bài cho học sinh', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: /hocsinh@lophoc.local/ }).check()
  await dialog.getByLabel('Tìm học sinh', { exact: true }).fill('minhtu@')
  await dialog.getByRole('checkbox', { name: /minhtu@lophoc.local/ }).check()
  await expect(dialog.getByRole('group', { name: 'Học sinh được giao · Đã chọn 2', exact: true })).toBeVisible()
  await dialog.getByLabel('Hướng dẫn').fill('Chọn câu trả lời đúng rồi nộp bài.')
  await dialog.getByLabel('Nội dung câu hỏi').fill('2 + 2?')
  await dialog.getByLabel('Các lựa chọn').fill('3\n4')
  await dialog.getByRole('combobox', { name: 'Đáp án đúng', exact: true }).selectOption('4')
  await dialog.getByRole('combobox', { name: 'Môn học', exact: true }).selectOption({ label: 'Toán học' })
  await dialog.getByRole('button', { name: 'Giao bài cho học sinh', exact: true }).click()
  await expect(dialog).toBeHidden()
  const assigned = (await (await teacher.request.get('/api/assignments')).json()).find((a: { title: string }) => a.title === title)
  expect(assigned.student_ids).toHaveLength(2)
  expect(assigned).not.toHaveProperty('class_ids')
  await login(outsider, 'hoangkhang@lophoc.local')
  expect((await outsider.request.get('/api/assignments/' + assigned.id)).status()).toBe(404)
  const outsiderAssignments = await (await outsider.request.get('/api/assignments')).json()
  expect(outsiderAssignments.some((a: { id: number }) => a.id === assigned.id)).toBe(false)
  await login(student, 'hocsinh@lophoc.local')
  const before = await (await student.request.get('/api/dashboard')).json()
  await student.getByRole('navigation').getByRole('button', { name: 'Bài tập', exact: true }).click()
  await student.getByRole('button', { name: 'Lớp 5', exact: true }).click()
  await student.getByRole('article').filter({ has: student.getByRole('heading', { name: title }) }).getByRole('button', { name: 'Xem bài tập' }).click()
  await student.getByRole('button', { name: 'Bắt đầu / tiếp tục làm bài' }).click()
  await student.getByRole('radio', { name: /4$/ }).check()
  await student.getByRole('button', { name: 'Lưu tiến độ', exact: true }).click()
  await expect(student.getByText('Đã lưu trên máy chủ', { exact: true })).toBeVisible()
  expect((await (await student.request.get('/api/dashboard')).json()).submissions).toBe(before.submissions)
  await student.getByRole('button', { name: 'Nộp bài', exact: true }).click()
  await student.getByRole('button', { name: 'Xác nhận nộp', exact: true }).click()
  await expect(student.getByText('10/10', { exact: true })).toBeVisible()
  await expect(student.getByRole('alert')).toHaveCount(0)
  expect((await (await student.request.get('/api/dashboard')).json()).submissions).toBe(before.submissions + 1)
  await teacher.setViewportSize({ width: 390, height: 900 })
  await teacher.getByRole('button', { name: 'Tạo bài tập có câu hỏi' }).click()
  expect(await teacher.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
  expect(classRequests).toEqual([])
  await teacherContext.close(); await studentContext.close(); await outsiderContext.close()
})
