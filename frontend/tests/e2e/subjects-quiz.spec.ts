import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, email: string) {
  await page.goto('/app/')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Mật khẩu', { exact: true }).fill('MatKhau123!')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Chào/ })).toBeVisible()
}

test('a teacher assigns a subject quiz and a student immediately sees its score and correct answers', async ({ browser }, testInfo) => {
  test.setTimeout(120_000)
  const teacherContext = await browser.newContext(), studentContext = await browser.newContext()
  try {
    const teacher = await teacherContext.newPage(), student = await studentContext.newPage()
    const errors: string[] = []
    teacher.on('pageerror', error => errors.push(error.message)); student.on('pageerror', error => errors.push(error.message))
    await login(teacher, 'giaovien@lophoc.local')
    await teacher.getByRole('navigation').getByRole('button', { name: 'Bài tập', exact: true }).click()
    const filter = teacher.getByRole('navigation', { name: 'Lọc theo môn học' })
    await filter.getByRole('button', { name: 'Toán học', exact: true }).click()
    await teacher.getByRole('button', { name: 'Tạo bài tập có câu hỏi' }).click()
    const dialog = teacher.getByRole('dialog'), title = 'Toán tự chấm ' + Date.now()
    await expect(dialog.getByRole('combobox', { name: 'Môn học', exact: true })).toHaveValue('1')
    await expect(dialog.getByRole('combobox', { name: 'Hình thức bài tập', exact: true })).toHaveValue('quiz')
    await expect(dialog.getByLabel('Hiện đáp án và giải thích sau khi nộp')).toBeChecked()
    await dialog.getByLabel('Tên bài tập').fill(title)
    await dialog.getByRole('checkbox', { name: /hocsinh@lophoc.local/ }).check()
    await dialog.getByLabel('Hướng dẫn').fill('Làm hai câu trắc nghiệm rồi nộp bài.')
    await dialog.getByLabel('Nội dung câu hỏi').fill('2 + 2 bằng bao nhiêu?')
    await dialog.getByLabel('Các lựa chọn').fill('3\n4')
    await dialog.getByRole('combobox', { name: 'Đáp án đúng', exact: true }).selectOption('4')
    await dialog.getByLabel('Giải thích', { exact: true }).fill('Hai cộng hai bằng bốn.')
    await dialog.getByRole('button', { name: 'Thêm câu hỏi', exact: true }).click()
    await dialog.getByLabel('Nội dung câu hỏi').nth(1).fill('3 + 3 bằng bao nhiêu?')
    await dialog.getByLabel('Các lựa chọn').nth(1).fill('5\n6')
    await dialog.getByRole('combobox', { name: 'Đáp án đúng', exact: true }).nth(1).selectOption('6')
    await dialog.getByRole('button', { name: 'Giao bài cho học sinh', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(teacher.getByRole('heading', { name: title, exact: true })).toBeVisible()
    await teacher.screenshot({ path: testInfo.outputPath('homework-subject-desktop.png') })
    await filter.getByRole('button', { name: 'Tiếng Anh', exact: true }).click()
    await expect(teacher.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
    await filter.getByRole('button', { name: 'Toán học', exact: true }).click()
    await expect(teacher.getByRole('heading', { name: title, exact: true })).toBeVisible()

    await login(student, 'hocsinh@lophoc.local')
    await student.getByRole('navigation').getByRole('button', { name: 'Bài tập', exact: true }).click()
    await student.getByRole('navigation', { name: 'Lọc theo môn học' }).getByRole('button', { name: 'Toán học', exact: true }).click()
    await student.getByRole('article').filter({ has: student.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: /Xem bài tập/ }).click()
    await student.getByRole('button', { name: 'Bắt đầu / tiếp tục làm bài' }).click()
    await student.getByRole('radio', { name: /3$/ }).check()
    await student.getByRole('radio', { name: /6$/ }).check()
    await expect(student.getByText('Đáp án đúng:', { exact: true })).toHaveCount(0)
    await student.getByRole('button', { name: 'Nộp bài', exact: true }).click()
    await student.getByRole('button', { name: 'Xác nhận nộp', exact: true }).click()
    await expect(student.getByText('5/10', { exact: true })).toBeVisible()
    await expect(student.getByText('Đã chấm điểm tự động. Không cần chờ giáo viên chấm.')).toBeVisible()
    const review = student.getByRole('list', { name: 'Chi tiết kết quả' })
    await expect(review.getByRole('listitem').first()).toContainText('Sai')
    await expect(review.getByRole('listitem').first()).toContainText('Đáp án đúng: 4')
    await expect(review.getByRole('listitem').first()).toContainText('Hai cộng hai bằng bốn.')
    await expect(review.getByRole('listitem').nth(1)).toContainText('Đúng')
    await student.setViewportSize({ width: 390, height: 900 })
    expect(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await student.screenshot({ path: testInfo.outputPath('quiz-result-mobile.png') })
    expect(errors).toEqual([])
  } finally { await teacherContext.close(); await studentContext.close() }
})

test('subject buttons filter teacher arcade rounds, collections and older games', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  await login(page, 'giaovien@lophoc.local')
  const subjects = await (await page.request.get('/api/subjects')).json()
  const math = subjects.find((subject: { name: string }) => subject.name === 'Toán học').id
  const english = subjects.find((subject: { name: string }) => subject.name === 'Tiếng Anh').id
  const students = await (await page.request.get('/api/users?role=student')).json()
  const token = (await (await page.request.get('/api/csrf')).json()).token
  const templates = await (await page.request.get('/api/arcade/templates')).json()
  const stamp = Date.now()
  for (const [id, label] of [[math, 'Math'], [english, 'English']] as const) {
    const content = { ...templates[0].content, subject_id: id, title: label + ' round ' + stamp }
    const response = await page.request.post('/api/arcade/rounds', { headers: { 'X-CSRF-TOKEN': token }, data: { content, expected_revision: 0 } })
    expect(response.ok(), await response.text()).toBe(true)
    const round = (await response.json()).id
    const collection = await page.request.post('/api/arcade/collections', { headers: { 'X-CSRF-TOKEN': token }, data: { title: label + ' collection ' + stamp, subject_id: id, round_ids: [round] } })
    expect(collection.ok(), await collection.text()).toBe(true)
    const game = await page.request.post('/api/games', { headers: { 'X-CSRF-TOKEN': token }, data: { title: label + ' legacy ' + stamp, subject_id: id, type: 'quiz', student_ids: [students[0].id], questions: [{ prompt: '2+2?', options: ['3', '4'], answer: '4' }] } })
    expect(game.ok(), await game.text()).toBe(true)
  }
  await page.getByRole('navigation').getByRole('button', { name: 'Trò chơi', exact: true }).click()
  const filter = page.getByRole('navigation', { name: 'Lọc theo môn học' })
  await filter.getByRole('button', { name: 'Tiếng Anh', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'English round ' + stamp, exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Math round ' + stamp, exact: true })).toHaveCount(0)
  await page.getByText('Bộ sưu tập ôn tập theo môn', { exact: true }).click()
  await expect(page.getByText('English collection ' + stamp, { exact: true })).toBeVisible()
  await expect(page.getByText('Math collection ' + stamp, { exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('arcade-subject-desktop.png') })
  await page.getByRole('button', { name: /Trò chơi trước đây/ }).click()
  await page.getByRole('navigation', { name: 'Lọc theo môn học' }).getByRole('button', { name: 'Tiếng Anh', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'English legacy ' + stamp, exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Math legacy ' + stamp, exact: true })).toHaveCount(0)
})
